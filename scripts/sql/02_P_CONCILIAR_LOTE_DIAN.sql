CREATE OR REPLACE PROCEDURE P_CONCILIAR_LOTE_DIAN(p_id_lote IN NUMBER) IS
    v_fecha_inicio DATE;
    v_fecha_fin DATE;
BEGIN
    SELECT FECHA_INICIO_ARCHIVO, FECHA_FIN_ARCHIVO INTO v_fecha_inicio, v_fecha_fin
      FROM AUDIT_DIAN_LOTES WHERE ID_LOTE = p_id_lote;

    -- 2. Limpieza CORREGIDA: Borrar fantasmas ANTES de resetear los estados
    DELETE FROM AUDIT_DIAN_DOCS
     WHERE ID_LOTE = p_id_lote AND ESTADO_CRUCE = 4;

    UPDATE AUDIT_DIAN_DOCS
       SET ESTADO_CRUCE = NULL, ID_DOC_ERP = NULL
     WHERE ID_LOTE = p_id_lote;

    -- 3. MATCH EXACTO (1) y DESCUADRE (2) con control de Nulos en Prefijo
    MERGE INTO AUDIT_DIAN_DOCS D
    USING (
        SELECT ID_DOCUMENTO, PREFIJO, FOLIO, GRUPO, NIT_TERCERO, TOTAL_ERP, IVA_ERP
        FROM (
            SELECT V.*, 
                   ROW_NUMBER() OVER(PARTITION BY PREFIJO, FOLIO, GRUPO, NIT_TERCERO ORDER BY ID_DOCUMENTO DESC) as rn
              FROM V_ERP_DIAN_BRIDGE V
             WHERE FECHA_DOCUMENTO BETWEEN (v_fecha_inicio - 30) AND (v_fecha_fin + 30)
        ) WHERE rn = 1
    ) E
    ON (
        D.ID_LOTE = p_id_lote
        AND NVL(TRIM(D.PREFIJO), 'X') = NVL(TRIM(E.PREFIJO), 'X')
        AND TRIM(D.FOLIO) = TRIM(E.FOLIO)
        AND D.GRUPO_FISCAL = E.GRUPO
        AND DECODE(D.GRUPO_FISCAL, 'EMITIDO', D.NIT_RECEPTOR, D.NIT_EMISOR) = E.NIT_TERCERO
    )
    WHEN MATCHED THEN
        UPDATE SET 
            D.ID_DOC_ERP = E.ID_DOCUMENTO,
            D.ESTADO_CRUCE = CASE 
                WHEN ABS(D.TOTAL - E.TOTAL_ERP) <= 5 AND ABS(D.IVA - E.IVA_ERP) <= 5 THEN 1
                ELSE 2
            END;

    -- 4. FALTANTES EN ERP (3 - Rojo)
    UPDATE AUDIT_DIAN_DOCS SET ESTADO_CRUCE = 3
     WHERE ID_LOTE = p_id_lote AND ID_DOC_ERP IS NULL;

    -- 5. FANTASMAS EN ERP (4 - Naranja)
    INSERT INTO AUDIT_DIAN_DOCS (
        ID_LOTE, TIPO_DOCUMENTO, PREFIJO, FOLIO, FECHA_EMISION,
        NIT_EMISOR, NIT_RECEPTOR, TOTAL, IVA, GRUPO_FISCAL, ESTADO_CRUCE, ID_DOC_ERP
    )
    SELECT
        p_id_lote, 'DOCUMENTO_ERP_NO_DIAN', E.PREFIJO, E.FOLIO, E.FECHA_DOCUMENTO,
        DECODE(E.GRUPO, 'RECIBIDO', E.NIT_TERCERO, 'NIT_PROPIO'),
        DECODE(E.GRUPO, 'EMITIDO', E.NIT_TERCERO, 'NIT_PROPIO'),
        E.TOTAL_ERP, E.IVA_ERP, E.GRUPO, 4, E.ID_DOCUMENTO
      FROM V_ERP_DIAN_BRIDGE E
     WHERE E.FECHA_DOCUMENTO BETWEEN v_fecha_inicio AND DECODE(TO_CHAR(v_fecha_fin,'HH24MI'),'0000',v_fecha_fin+0.99999,v_fecha_fin)
       AND NOT EXISTS (
           SELECT 1 FROM AUDIT_DIAN_DOCS D
            WHERE D.ID_LOTE = p_id_lote AND D.ID_DOC_ERP = E.ID_DOCUMENTO
       );

    COMMIT;
END P_CONCILIAR_LOTE_DIAN;
